package io.github.afonsorocha10.delivery.delivery;

import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Version;

/**
 * A delivery and its lifecycle state, stored in the {@code delivery} table (see V1__create_delivery.sql).
 * State changes only through {@link #transitionTo}, so the status rules cannot be bypassed; there are no setters.
 */
@Entity
@Table(name = "delivery")
public class Delivery {

    /** Assigned by the application, not generated by the database. */
    @Id
    private UUID id;

    @Column(nullable = false, length = 100)
    private String recipientName;

    @Column(nullable = false, length = 255)
    private String address;

    /** Stored by name, so reordering the enum constants cannot corrupt existing rows. */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private DeliveryStatus status;

    /**
     * Optimistic locking: every update checks and increments it, so a concurrent update fails instead of being lost.
     * A wrapper type on purpose: {@code null} tells Spring Data that the entity is new (INSERT, not SELECT + UPDATE).
     */
    @Version
    private Long version;

    @Column(nullable = false)
    private Instant createdAt;

    @Column(nullable = false)
    private Instant updatedAt;

    /** Required by JPA; not for application code. */
    protected Delivery() {
    }

    private Delivery(UUID id, String recipientName, String address, Instant now) {
        this.id = id;
        this.recipientName = recipientName;
        this.address = address;
        this.status = DeliveryStatus.CREATED;
        this.createdAt = now;
        this.updatedAt = now;
    }

    /**
     * Creates a new delivery in {@link DeliveryStatus#CREATED}.
     *
     * @param now the creation time; passed in (not read here) so tests and demo data can control it
     */
    public static Delivery create(String recipientName, String address, Instant now) {
        return new Delivery(UUID.randomUUID(), recipientName, address, toDatabasePrecision(now));
    }

    /**
     * Moves the delivery to {@code target} if the lifecycle allows it.
     *
     * @throws InvalidStatusTransitionException if the transition is not allowed; the delivery is left unchanged
     */
    public void transitionTo(DeliveryStatus target, Instant now) {
        if (!status.canTransitionTo(target)) {
            throw new InvalidStatusTransitionException(id, status, target);
        }
        this.status = target;
        this.updatedAt = toDatabasePrecision(now);
    }

    /** PostgreSQL stores microseconds; truncating keeps the in-memory value equal to what is read back. */
    private static Instant toDatabasePrecision(Instant instant) {
        return instant.truncatedTo(ChronoUnit.MICROS);
    }

    // Record-style accessor names, as before, so callers did not have to change.

    public UUID id() {
        return id;
    }

    public String recipientName() {
        return recipientName;
    }

    public String address() {
        return address;
    }

    public DeliveryStatus status() {
        return status;
    }

    public Instant createdAt() {
        return createdAt;
    }

    public Instant updatedAt() {
        return updatedAt;
    }

    /** Identity is the id alone: a delivery stays equal to itself after its status changes. */
    @Override
    public boolean equals(Object other) {
        return this == other || (other instanceof Delivery delivery && id.equals(delivery.id));
    }

    @Override
    public int hashCode() {
        return id.hashCode();
    }

    @Override
    public String toString() {
        return "Delivery[id=" + id + ", status=" + status + ", version=" + version + "]";
    }
}
